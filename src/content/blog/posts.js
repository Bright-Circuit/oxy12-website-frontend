export function getPublishedPosts() {
  return blogPosts
    .filter((post) => post.status === "published")
    .sort((a, b) => {
      const dateDifference =
        new Date(b.publishedDate).getTime() -
        new Date(a.publishedDate).getTime();

      if (dateDifference !== 0) return dateDifference;

      const orderDifference =
        (b.publicationOrder ?? 0) - (a.publicationOrder ?? 0);

      if (orderDifference !== 0) return orderDifference;

      return a.slug.localeCompare(b.slug);
    });
}

export const BLOG_POSTS_PER_PAGE = 6;

export function getBlogPageCount() {
  return Math.max(
    1,
    Math.ceil(getPublishedPosts().length / BLOG_POSTS_PER_PAGE),
  );
}

export function getPublishedPostsForPage(pageNumber) {
  const start = (pageNumber - 1) * BLOG_POSTS_PER_PAGE;
  return getPublishedPosts().slice(start, start + BLOG_POSTS_PER_PAGE);
}

export function getPublishedPostBySlug(slug) {
  return getPublishedPosts().find((post) => post.slug === slug);
}

export function getRelatedPublishedPosts(post) {
  if (!post) return [];

  const relatedSlugs = new Set(post.relatedPosts ?? []);
  return getPublishedPosts().filter(
    (candidate) =>
      candidate.slug !== post.slug && relatedSlugs.has(candidate.slug),
  );
}
